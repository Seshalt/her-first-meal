export type SiteCopy = typeof DEFAULT_SITE_COPY;
export type SiteCopyKey = keyof SiteCopy;

export function mergeSite(partial: Partial<SiteCopy> | null | undefined): SiteCopy {
  const out = { ...DEFAULT_SITE_COPY };
  if (!partial) return out;
  for (const key of Object.keys(DEFAULT_SITE_COPY) as SiteCopyKey[]) {
    const value = partial[key];
    if (typeof value === "string") out[key] = value;
  }
  return out;
}

export function lines(value: string): string[] {
  return value
    .split("\n")
    .map((s) => s.trim())
    .filter(Boolean);
}

